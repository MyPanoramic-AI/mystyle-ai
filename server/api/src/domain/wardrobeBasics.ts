const STYLE_CAPSULES: Record<string, StarterBasicTemplate[]> = {
  'Classic & Elegant': CLASSIC_ELEGANT,
  'Modern & Minimal': MODERN_MINIMAL,
  'Casual & Comfortable': CASUAL_COMFORTABLE,
  'Trendy & Bold': TRENDY_BOLD,
  'Smart & Professional': SMART_PROFESSIONAL,
  'Romantic & Feminine': ROMANTIC_FEMININE,
  'Sporty & Active': SPORTY_ACTIVE,
  'Chic & Sophisticated': CHIC_SOPHISTICATED,
};

const STYLE_ALIASES: Record<string, string> = {
  classic: 'Classic & Elegant',
  elegant: 'Classic & Elegant',
  tailored: 'Smart & Professional',
  minimal: 'Modern & Minimal',
  modern: 'Modern & Minimal',
  casual: 'Casual & Comfortable',
  comfortable: 'Casual & Comfortable',
  trendy: 'Trendy & Bold',
  bold: 'Trendy & Bold',
  professional: 'Smart & Professional',
  smart: 'Smart & Professional',
  romantic: 'Romantic & Feminine',
  feminine: 'Romantic & Feminine',
  sporty: 'Sporty & Active',
  active: 'Sporty & Active',
  chic: 'Chic & Sophisticated',
  sophisticated: 'Chic & Sophisticated',
};

export function resolveStarterStyleKey(styles: string[]): string {
  for (const style of styles) {
    const trimmed = style.trim();
    if (STYLE_CAPSULES[trimmed]) return trimmed;
    const lower = trimmed.toLowerCase();
    for (const [alias, key] of Object.entries(STYLE_ALIASES)) {
      if (lower.includes(alias)) return key;
    }
  }
  return 'Classic & Elegant';
}

export function starterBasicsForStyles(styles: string[]): StarterBasicTemplate[] {
  const key = resolveStarterStyleKey(styles);
  return STYLE_CAPSULES[key] ?? CLASSIC_ELEGANT;
}

export interface StyleCapsulePiece extends StarterBasicTemplate {
  sizeLabel: string | null;
}

/** The 10 basics someone should own for their chosen style. Does not write to the wardrobe. */
export function styleCapsuleForProfile(styles: string[], sizes: StarterSizeHints): { style: string; pieces: StyleCapsulePiece[] } {
  const style = resolveStarterStyleKey(styles);
  const pieces = starterBasicsForStyles(styles).slice(0, 10).map((basic) => ({
    ...basic,
    sizeLabel: sizeLabelFor(basic, sizes),
  }));
  return { style, pieces };
}

function sizeLabelFor(template: StarterBasicTemplate, sizes: StarterSizeHints): string | null {
  if (!template.sizeFrom) return null;
  const value = sizes[template.sizeFrom];
  return typeof value === 'string' && value.trim() ? value.trim().slice(0, 40) : null;
}

/**
 * Seeds exactly 10 capsule basics when the wardrobe is empty.
 * Returns how many items were created (0 if already populated).
 */
export function seedStarterWardrobeBasics(
  db: Sql,
  userId: string,
  styles: string[],
  sizes: StarterSizeHints,
  now: number,
  styleLabel?: string,
): number {
  if (listWardrobe(db, userId).length > 0) return 0;
  const basics = starterBasicsForStyles(styles).slice(0, 10);
  const label = styleLabel ?? resolveStarterStyleKey(styles);
  for (const basic of basics) {
    createWardrobeItem(db, userId, {
      name: basic.name,
      category: basic.category,
      subcategory: basic.subcategory,
      brand: basic.brand,
      colour: basic.colour,
      colourHex: basic.colourHex,
      seasons: basic.seasons,
      occasions: basic.occasions,
      fabric: basic.fabric,
      careNote: basic.careNote,
      pairingNotes: basic.pairingNotes,
      imageUrl: basic.imageUrl,
      sizeLabel: sizeLabelFor(basic, sizes),
      notes: `Starter wardrobe basic · matched to ${label}`,
      isCapsule: true,
      isFavorite: false,
      timesWorn: 0,
    }, now);
  }
  return basics.length;
}

/** Ensures a completed profile with an empty wardrobe receives style-matched basics. */
export function ensureStarterWardrobeBasics(
  db: Sql,
  userId: string,
  profile: {
    styles?: unknown;
    onboardingStatus?: unknown;
    completionStatus?: unknown;
    sizes?: { tops?: unknown; bottoms?: unknown; dress?: unknown; shoe?: unknown } | null;
  },
  now: number,
): number {
  const ready = profile.onboardingStatus === 'completed' || profile.completionStatus === 'complete';
  if (!ready) return 0;
  const styles = Array.isArray(profile.styles)
    ? profile.styles.filter((entry): entry is string => typeof entry === 'string' && entry.trim().length > 0)
    : [];
  if (!styles.length) return 0;
  const sizes: StarterSizeHints = {
    tops: typeof profile.sizes?.tops === 'string' ? profile.sizes.tops : null,
    bottoms: typeof profile.sizes?.bottoms === 'string' ? profile.sizes.bottoms : null,
    dress: typeof profile.sizes?.dress === 'string' ? profile.sizes.dress : null,
    shoe: typeof profile.sizes?.shoe === 'string' ? profile.sizes.shoe : null,
  };
  return seedStarterWardrobeBasics(db, userId, styles, sizes, now);
}
